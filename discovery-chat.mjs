const CHAT_COMPONENTS = [
  ['slopeP50Deg', 'Median slope (p50)'],
  ['slopeP90Deg', 'Slope (p90)'],
  ['reliefP95P5M', 'Relief (p95–p5)'],
  ['triMeanM', 'Mean terrain ruggedness (TRI)'],
  ['roughness', 'Radar roughness'],
  ['thermalAmplitudeK', 'Daily thermal amplitude'],
];

export function buildDiscoveryChatContext({ discovery, target, candidate, comparison }) {
  if (!discovery || !target || !candidate || !comparison) return null;
  const compactThermal = (thermal) => thermal ? {
    amplitudeK: thermal.amplitudeK ?? null,
    minK: thermal.minK ?? null,
    maxK: thermal.maxK ?? null,
    kind: thermal.kind || null,
    source: thermal.source || null,
  } : null;
  const components = (comparison.components || []).map((component) => ({
    key: component.key,
    label: CHAT_COMPONENTS.find(([key]) => key === component.key)?.[1] || component.label || component.key,
    earth: component.earth ?? null,
    target: component.target ?? null,
    score: component.score ?? null,
    weight: component.weight ?? null,
    unit: component.unit || null,
  }));
  const [latitude, longitude] = candidate.center || [];
  return {
    domain: 'earth-analogue-discovery',
    discovery: {
      target: {
        id: discovery.targetId,
        name: target.name || target.title || discovery.targetId,
        body: target.body || discovery.body || null,
        thermal: compactThermal(target.thermal),
      },
      candidate: {
        id: candidate.id,
        rank: candidate.rank ?? null,
        name: candidate.place?.name || candidate.name || null,
        country: candidate.place?.country || null,
        center: Number.isFinite(latitude) && Number.isFinite(longitude) ? [latitude, longitude] : null,
        scaleMeters: candidate.scaleMeters ?? candidate.extentMeters ?? null,
        thermal: compactThermal(candidate.thermal),
        aridity: candidate.aridity || null,
        dataset: candidate.dataset || null,
        provenance: candidate.provenance || null,
        notes: candidate.notes || null,
      },
      comparison: {
        index: comparison.index ?? null,
        comparable: comparison.comparable ?? null,
        includesThermalAmplitude: components.some((component) => component.key === 'thermalAmplitudeK'),
        components,
        caveats: comparison.caveats || discovery.caveats || null,
      },
      method: {
        description: 'The displayed index is a terrain-comparison index (0–100), not planetary similarity. It compares only the available component metrics and renormalizes their displayed weights. Slope, relief and TRI use a 100 × smaller absolute value / larger absolute value component score with metric-specific floors. Radar roughness in dB uses an exponential difference score. Thermal amplitude, when present on both sides, uses a ratio score with a 1 K floor and compares Earth 2 m air climatology with planetary surface values; it is not physical equivalence.',
        limitations: [
          'A candidate generated by this grid is not a verified or published field-test site.',
          'The comparison does not establish geological, material, operational, or planetary equivalence.',
          'Missing values remain unknown and must not be interpreted as zero.',
        ],
      },
    },
  };
}

export function discoveryChatContextKey({ targetId, candidateId }) {
  return `${targetId || 'none'}:${candidateId || 'none'}`;
}

export function answerDiscoveryLocally(question, context) {
  const scenario = context?.discovery;
  const comparison = scenario?.comparison;
  if (!scenario || !comparison) return 'No candidate comparison is selected yet.';
  const q = String(question).toLocaleLowerCase();
  if (/why|how|formula|calculate|score|indice|índice|calcula|puntu|formula|fórmula/.test(q)) {
    const thermalNote = comparison.includesThermalAmplitude ? ' This comparison also includes thermal amplitude, which is not a geometric metric.' : '';
    return `${scenario.method.description}${thermalNote} The displayed index for ${scenario.candidate.name || scenario.candidate.id} against ${scenario.target.name} is ${comparison.index ?? 'unknown (not enough comparable data)'}.`;
  }
  if (/source|data|dataset|fuente|datos|provenance|procedencia/.test(q)) {
    const candidate = scenario.candidate;
    const target = scenario.target;
    return `The candidate uses ${candidate.dataset || 'no dataset recorded'}${candidate.provenance?.length ? `; provenance: ${candidate.provenance.map((item) => item.label || item.url).filter(Boolean).join('; ')}` : ''}. The target is ${target.name} (${target.body || 'body not recorded'}). Missing fields remain unknown; consult Sources and limits for details.`;
  }
  if (/limit|caveat|unknown|missing|limite|límite|falta|desconoc|cuidado/.test(q)) {
    return scenario.method.limitations.join(' ') + (comparison.caveats?.length ? ` Comparison caveats: ${comparison.caveats.join(' ')}` : ' No additional comparison caveats were supplied.');
  }
  const componentText = comparison.components.length
    ? comparison.components.map((item) => `${item.label}: Earth ${item.earth ?? 'unknown'}, target ${item.target ?? 'unknown'}${item.unit ? ` ${item.unit}` : ''}; component score ${item.score ?? 'unknown'} with ${item.weight == null ? 'unknown' : `${Math.round(item.weight * 100)}%`} weight`).join('. ')
    : 'No comparable metric components are available.';
  const metricKind = comparison.includesThermalAmplitude ? 'terrain-comparison index' : 'geometric similarity index';
  return `${scenario.candidate.name || scenario.candidate.id} compared with ${scenario.target.name}: ${metricKind} ${comparison.index ?? 'unknown'}. ${componentText} This is not evidence of planetary equivalence.`;
}
