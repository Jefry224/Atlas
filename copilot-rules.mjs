import { BODY_ENV, solarPowerW } from './sim-physics.mjs';

const finite = (v) => typeof v === 'number' && Number.isFinite(v);
const get = (obj, path) => path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
const fmt = (v, d = 1) => (finite(v) ? Number(v.toFixed(d)).toLocaleString('en-US') : '—');
const kToC = (k) => k - 273.15;
const BODY_LABEL = { earth: 'Earth', moon: 'Moon', mars: 'Mars' };

export const DISCLAIMER = 'Answer generated by local rules (no AI), using only the context data. Illustrative prototype thresholds; it does not replace an engineering or safety analysis.';

const INTENTS = {
  landing: /aterriz|descens|landing|combustible|propelente|fuel|zona.{0,12}contacto|contacto/,
  breakdown: /ruptura|gravedad|peso|calibra|descarga|presion|vacio|ionizante|breakdown|offload|gravity|vacuum/,
  thermal: /termic|temperatur|calor|frio|congel|helad|thermal|temperature|heat|cold|freez/,
  energy: /energ|bateri|battery|solar|power|potencia|carga|charg|panel|irradian/,
  terrain: /pendient|vuelco|volc|inclin|navega|ruta|terreno|slope|tip|rollover|pitch|roll|navigat|route|terrain|cabece|alabeo/,
  wind: /viento|polvo|rafaga|tormenta|wind|dust|gust|storm/,
  similarity: /similit|similar|compar|analog|parec|indice|index|match/,
  window: /ventana|cuando|pronostic|72 ?h|probar|saltacion|proceso|forecast|window|when/,
  summary: /resumen|estado|general|summary|status|overview|go\s*\/?\s*no|despliegue|deploy|riesgo|risk/,
};

const normalize = (s) => String(s ?? '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');

export function detectIntents(question) {
  const q = normalize(question);
  const found = Object.keys(INTENTS).filter((k) => k !== 'summary' && INTENTS[k].test(q));
  return found.length ? found : ['summary'];
}

function telemetryProvenance(t) {
  if (!t) return 'no telemetry';
  if (t.live === true) return `live · ${t.provider || 'unknown provider'}${t.cached ? `, cached ${fmt(t.ageSeconds, 0)} s` : ''}`;
  if (t.provider === 'snapshot') return `saved snapshot${t.observedAt ? ` from ${t.observedAt}` : ''}, not live`;
  return `not live · ${t.provider || 'unknown origin'}`;
}
const THERMAL_KIND = { live: 'live', diviner: 'LRO Diviner', literature: 'literature', model: 'model' };
const thermalProvenance = (th) => (th ? `${THERMAL_KIND[th.kind] || th.kind || 'unlabeled origin'}${th.source ? ` · ${th.source}` : ''}` : 'no data');

function makeReport(ctx) {
  const grounded = new Set();
  const missing = new Set();
  const use = (path) => { const v = get(ctx, path); if (v === undefined || v === null) { missing.add(path); return undefined; } grounded.add(path); return v; };
  const num = (path) => { const v = get(ctx, path); if (finite(v)) { grounded.add(path); return v; } missing.add(path); return undefined; };
  return { grounded, missing, use, num };
}

function thermalSection(ctx, r, flags) {
  const lines = [];
  const level = r.use('rover.thermal.level');
  const margin = r.num('rover.thermal.marginK');
  if (level) {
    lines.push(`Rover: thermal state ${level.toUpperCase()}${finite(margin) ? `, margin ${fmt(margin, 0)} K` : ''}${ctx.rover?.thermal?.text ? ` — ${ctx.rover.thermal.text.replace(/\.$/, '')}` : ''}.`);
    if (level === 'critical') flags.nogo.push('thermal out of range');
    else if (level === 'caution') flags.caution.push('reduced thermal margin');
  }
  const tC = r.num('earth.telemetry.values.temperatureC');
  if (finite(tC)) lines.push(`Earth analog: ${fmt(tC)} °C (${telemetryProvenance(ctx.earth?.telemetry)}).`);
  const et = ctx.earth?.thermal;
  if (et && finite(et.minK) && finite(et.maxK)) { r.use('earth.thermal'); lines.push(`Earth analog, reference range: ${fmt(kToC(et.minK), 0)} to ${fmt(kToC(et.maxK), 0)} °C (${thermalProvenance(et)}).`); }
  const tt = ctx.target?.thermal;
  if (tt && finite(tt.minK) && finite(tt.maxK)) {
    r.use('target.thermal');
    lines.push(`Target ${ctx.target?.name || ''}: ${fmt(tt.minK, 0)}–${fmt(tt.maxK, 0)} K (${fmt(kToC(tt.minK), 0)} to ${fmt(kToC(tt.maxK), 0)} °C; ${thermalProvenance(tt)}).`.replace('  ', ' '));
    if (tt.minK < 233) lines.push('At the target, the minimum drops below −40 °C: a rover with this operating window would need heating or hibernation; the Earth analog does not reproduce that cold.');
  } else r.missing.add('target.thermal');
  if (!lines.length) lines.push('No thermal data in the context: thermal risk cannot be assessed.');
  return { title: 'Thermal risk', lines };
}

function energySection(ctx, r, flags) {
  const lines = [];
  const bat = r.num('rover.batteryPct');
  const solar = r.num('rover.solarW');
  if (finite(bat)) {
    lines.push(`Rover battery: ${fmt(bat, 0)} %${finite(solar) ? `; simulated solar generation ${fmt(solar, 0)} W` : ''}.`);
    if (bat < 15) flags.nogo.push('battery < 15 %'); else if (bat < 30) flags.caution.push('battery < 30 %');
  } else if (finite(solar)) lines.push(`Simulated solar generation: ${fmt(solar, 0)} W.`);
  const irr = r.num('earth.telemetry.values.solarRadiationWm2');
  if (finite(irr)) {
    const cloud = get(ctx, 'earth.telemetry.values.cloudCoverPct');
    if (finite(cloud)) r.use('earth.telemetry.values.cloudCoverPct');
    lines.push(`Radiation at the analog: ${fmt(irr, 0)} W/m²${finite(cloud) ? `, cloud cover ${fmt(cloud, 0)} %` : ''} (${telemetryProvenance(ctx.earth?.telemetry)}). With 2 m² at 28 %: ≈ ${fmt(solarPowerW({ irradianceWm2: irr }), 0)} W.`);
  }
  const body = ctx.target?.body;
  const sc = finite(ctx.target?.environment?.solarConstantWm2) ? (r.use('target.environment.solarConstantWm2'), ctx.target.environment.solarConstantWm2) : BODY_ENV[body]?.solarConstantWm2;
  if (finite(sc)) {
    lines.push(`Target (${BODY_LABEL[body] || body}): solar constant ${fmt(sc, 0)} W/m² ⇒ upper bound ≈ ${fmt(solarPowerW({ irradianceWm2: sc }), 0)} W with the same panel at normal incidence (no atmosphere, dust or real sun angle).`);
    if (body === 'moon' && /shackleton|polar|south\s*pole|\bsur\b/i.test(`${ctx.target?.id} ${ctx.target?.name}`)) lines.push('At the lunar south pole the Sun is grazing and there is permanent shadow: real power can be much lower or zero.');
  }
  if (!lines.length) lines.push('No battery or radiation data in the context: the energy balance cannot be assessed.');
  return { title: 'Energy', lines };
}

function terrainSection(ctx, r, flags) {
  const lines = [];
  const pitch = r.num('rover.pitchDeg'), roll = r.num('rover.rollDeg'), slope = r.num('rover.slopeDeg');
  if (finite(pitch) || finite(roll)) lines.push(`Attitude: pitch ${fmt(pitch)}°, roll ${fmt(roll)}°${finite(slope) ? `, local slope ${fmt(slope)}°` : ''}.`);
  else if (finite(slope)) lines.push(`Local slope: ${fmt(slope)}°.`);
  const tilt = Math.max(Math.abs(finite(pitch) ? pitch : 0), Math.abs(finite(roll) ? roll : 0), finite(slope) ? slope : 0);
  if (tilt >= 25) { flags.nogo.push('tilt ≥ 25°'); lines.push('Tilt ≥ 25° (illustrative threshold): rollover risk; recommend backing up and replanning the route.'); }
  else if (tilt >= 12) { flags.caution.push('tilt ≥ 12°'); lines.push('Tilt ≥ 12° (illustrative threshold): reduce speed and avoid cross-slope traverses.'); }
  else if (finite(pitch) || finite(roll) || finite(slope)) lines.push('Tilt below 12°: low at regional scale, but the ~30 m DEM cannot see rocks or boulders.');
  const e90 = r.num('earth.metrics.slopeP90Deg'), t90 = r.num('target.metrics.slopeP90Deg');
  if (finite(e90) || finite(t90)) lines.push(`Window slope p90: Earth ${fmt(e90)}° vs target ${fmt(t90)}°.`);
  if (!lines.length) lines.push('No rover attitude or slope metrics in the context.');
  return { title: 'Slope and navigation', lines };
}

function windSection(ctx, r, flags) {
  const lines = [];
  const w = r.num('earth.telemetry.values.windSpeedMs');
  const g = get(ctx, 'earth.telemetry.values.windGustMs');
  if (finite(g)) r.use('earth.telemetry.values.windGustMs');
  if (finite(w) || finite(g)) {
    lines.push(`Wind at the analog: ${fmt(w)} m/s${finite(g) ? `, gusts ${fmt(g)} m/s` : ''} (${telemetryProvenance(ctx.earth?.telemetry)}).`);
    const peak = Math.max(finite(w) ? w : 0, finite(g) ? g : 0);
    if (peak >= 15) { flags.caution.push('gusts ≥ 15 m/s'); lines.push('Gusts ≥ 15 m/s (illustrative threshold): airborne dust, risk to optics and panels.'); }
  } else lines.push('No analog wind data in the context.');
  const body = ctx.target?.body;
  if (body === 'moon') lines.push('Lunar target: no wind; the dust risk is electrostatically clinging regolith, which the analog does not reproduce.');
  if (body === 'mars') lines.push('Martian target: thin atmosphere (≈ 0.6 kPa); wind pushes little but carries fine dust. There is no live target wind in this context.');
  return { title: 'Wind and dust', lines };
}

const WINDOW_KIND = { thermal: 'thermal (diurnal curve shape)', aeolian: 'aeolian (saltation)', freeze: 'freezing', cold: 'cold (thermal minimum with the lowest radiation)' };
function localTime(iso, offset) {
  const ms = Date.parse(iso);
  if (!Number.isFinite(ms)) return '—';
  const d = new Date(ms + (finite(offset) ? offset : 0) * 1000);
  const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  return `${days[d.getUTCDay()]} ${String(d.getUTCDate()).padStart(2, '0')} ${String(d.getUTCHours()).padStart(2, '0')}:00`;
}
function windowSection(ctx, r) {
  const lines = [];
  const p = ctx.processes;
  if (!p || typeof p !== 'object') {
    r.missing.add('processes');
    lines.push('No 72 h forecast in the context: a test window cannot be indicated.');
    return { title: 'Test window (72 h)', lines };
  }
  r.use('processes');
  const off = p.utcOffsetSeconds;
  lines.push(`Forecast: ${p.live ? `live · ${p.provider || 'provider'}` : `archived (${p.provider || 'snapshot'}), the hours may have passed`}. Analog local times${p.timezone ? ` (${p.timezone})` : ''}.`);
  if (p.best) {
    const w = p.best;
    lines.push(`Recommended window: ${WINDOW_KIND[w.kind] || w.kind}, ${localTime(w.start, off)} → ${localTime(w.end, off)} (${fmt(w.hours, 0)} h)${finite(w.score) ? `, match ${fmt(w.score, 0)}/100` : ''}${w.phase ? `, ${w.phase} phase` : ''}.`);
  } else lines.push('No window meets the thresholds in the next 72 h.');
  const others = [...(p.thermalWindows || []), ...(p.aeolianWindows || [])].filter((w) => w && (!p.best || w.start !== p.best.start)).slice(0, 2);
  for (const w of others) lines.push(`· Alternativa ${WINDOW_KIND[w.kind] || w.kind}: ${localTime(w.start, off)} → ${localTime(w.end, off)} (${fmt(w.hours, 0)} h).`);
  if (p.currentSaltation) lines.push(`Saltation now: ${({ sustained: 'sustained', intermittent: 'intermittent (gusts)', suppressed: 'suppressed by moisture', none: 'not active', unknown: 'no data' })[p.currentSaltation] || p.currentSaltation}.`);
  if (finite(p.freezeEvents)) lines.push(`Surface 0 °C crossings in 72 h: ${fmt(p.freezeEvents, 0)}${finite(p.freezeThawCycles) ? ` (freeze-thaw cycles: ${fmt(p.freezeThawCycles, 0)})` : ''}.`);
  if (Array.isArray(p.caveats) && p.caveats[1]) lines.push(`Advertencia: ${p.caveats[1]}`);
  return { title: 'Test window (72 h)', lines };
}

function similaritySection(ctx, r) {
  const lines = [];
  const s = ctx.similarity;
  if (s && typeof s === 'object') {
    r.use('similarity');
    lines.push(finite(s.index) ? `Geometric similarity index: ${fmt(s.index, 0)}/100${s.comparable === false ? ' (not comparable at scale, indicative)' : ''}.` : 'Geometric similarity index unavailable (missing metrics).');
    for (const c of (s.components || []).slice(0, 5)) lines.push(`· ${c.label}: Earth ${fmt(c.earth, 2)}${c.unit && c.unit !== '°' ? ' ' : ''}${c.unit || ''} vs target ${fmt(c.target, 2)}${c.unit && c.unit !== '°' ? ' ' : ''}${c.unit || ''} → ${fmt(c.score, 0)}/100 (weight ${fmt(c.weight * 100, 0)} %).`);
    if (Array.isArray(s.caveats) && s.caveats.length) lines.push(`Caveat: ${s.caveats[0]}`);
  } else {
    r.missing.add('similarity');
    lines.push('No similarity calculation in the context. Reminder: it would be geometric only, never planetary.');
  }
  return { title: 'Geometric similarity', lines };
}

function breakdownSection(ctx, r) {
  const a = ctx.analogyAudit;
  if (!a) { r.missing.add('analogyAudit'); return { title: 'Analog breakdown', lines: ['No Module 2 audit in the context.'] }; }
  r.use('analogyAudit');
  const lines = ['Local audit: status per parameter, no global physical index.'];
  for (const row of (a.matrix || []).filter(row => row.status === 'breakdown' || row.status === 'unknown').slice(0, 9)) lines.push(`${row.id}: ${row.status} — ${row.breakdown}`);
  const c = a.calibration;
  if (c) {
    r.use('analogyAudit.calibration');
    lines.push(`Test equipment: ${c.equipment}; calculation body ${BODY_LABEL[c.targetBody] || c.targetBody}; ${c.kind === 'mission-config' ? 'mission configuration (prototype-config) and references with explicit gaps' : 'parameters as user hypotheses'}.`);
    if (finite(c.massKg)) lines.push(`Mass ${fmt(c.massKg, 2)} kg; it does not change with gravity.`);
    if (finite(c.gravity?.targetWeightN)) lines.push(`Target weight ${fmt(c.gravity.targetWeightN, 2)} N; vertical offload ${fmt(c.gravity.offloadForceN, 2)} N; ratio g_target/g_Earth ${fmt(c.gravity.targetToEarthRatio, 5)}.`);
    else lines.push('Insufficient data for static load.');
  } else lines.push('Calibration has no valid parameters; correct the inputs.');
  lines.push(a.limitation || 'Offloading only matches static load; it does not reproduce dynamics, terramechanics, vacuum or radiation.');
  return { title: 'Analog breakdown', lines };
}


function landingSection(ctx,r) {
  const root=ctx.landing ? 'landing' : 'analogyAudit.landing';
  const l=r.use(root),lines=[];
  if (!l) return {title:'Final descent',lines:['No descent test in the current session: profiles, regional plan and simulated states are missing. No touchdown or available fuel is inferred.']};
  lines.push(`Mission phase: ${r.use(root+'.phase')}; start UTC ${r.use(root+'.startedAtUTC') || 'not provided'}. UTC and descent SIM are independent of the rover SIM ×20.`);
  const targetFirst=l.missionMode==='target-first';
  if (targetFirst) {
    r.use(root+'.missionMode'); r.use(root+'.primarySide');
    const origins=r.use(root+'.explorationOrigins'),mirror=r.use(root+'.mirrorAvailable');
    lines.push('We choose the lunar/Martian destination because that is where the lander descends, and its nominal touchdown governs deployment and exploration. The user chooses the target zone and fuel; Earth prepares and rehearses rover control without choosing a second landing.');
    lines.push(origins?.earth ? `Earth test origin: x ${fmt(origins.earth.x)} m, z ${fmt(origins.earth.z)} m; DEM ${origins.earth.gridId}, role ${origins.earth.role}. Surface reference, no lander touchdown.` : 'No valid Earth test origin: the target descent is independent; the mirror is limited.');
    lines.push(origins?.target ? `Target origin: own touchdown x ${fmt(origins.target.x)} m, z ${fmt(origins.target.z)} m; DEM ${origins.target.gridId}, role ${origins.target.role}.` : 'No nominal target touchdown: deployment and exploration are not enabled.');
    lines.push(`Mirror ${mirror?'available':'limited: requires both origins and target touchdown'}; target position = targetTouchdown + (roverEarth − earthOrigin). Each body keeps its own georeference; there is no geographic homology.`);
  }
  for (const side of targetFirst?['target','earth']:['earth','target']) {
    if (targetFirst && side==='earth') {
      lines.push('Earth analog/reference: Not applicable: no Earth descent. The Earth profile/plan is a reference; the test rover keeps Earth body and coordinates. Earth weather and proposed instruments are not readings of the planet; there is no real hardware telemetry.');
      continue;
    }
    const run=r.use(`${root}.runs.${side}`), profile=r.use(`${root}.profiles.${side}`), plan=r.use(`${root}.plans.${side}`);
    const label=side==='earth'?'Virtual Earth':'Target';
    if (!run) {lines.push(`${label}: no lander state; check DEM/profile availability. No outcome is inferred.`);continue;}
    lines.push(`${label}: phase ${run.phase || 'not provided'}, SIM ${fmt(run.simSeconds)} s; AGL ${fmt(run.altitudeM)} m; vertical speed ${fmt(run.verticalSpeedMs)} m/s and horizontal ${fmt(run.horizontalSpeedMs)} m/s. Propellant ${fmt(run.propellantKg)} kg; thrust ${fmt(run.thrustN)} N.`);
    if (run.outcome) lines.push(`Model outcome ${label}: ${typeof run.outcome==='object'?JSON.stringify(run.outcome):run.outcome}.`);
    if (run.contact) lines.push(`Proposed touchdown check ${label}: ${run.contact.withinTolerances===true?'within model tolerances':run.contact.withinTolerances===false?'outside model tolerances':'tolerance result not provided'}. Does not certify terrain.`);
    if (profile) {
      lines.push(`Lander profile ${profile.id}: dry mass ${fmt(profile.dryMassKg)} kg, initial propellant ${fmt(profile.propellantKg)} kg, Isp ${fmt(profile.ispSeconds)} s, max thrust ${fmt(profile.thrustMaxN)} N. Proposal separate from the 350 kg rover.`);
      lines.push(`Proposed tolerances: vertical touchdown ${fmt(profile.touchdownVerticalSpeedMs)} m/s, horizontal ${fmt(profile.touchdownHorizontalSpeedMs)} m/s, tilt ${fmt(profile.touchdownTiltDeg)}°. These are not certified limits.`);
      const sources=profile.sources || profile.source;
      if (sources) lines.push(`Profile sources ${label}: ${typeof sources==='object'?JSON.stringify(sources):sources}.`);
    } else lines.push(`${label}: profile not provided; ranges and fuel capacity cannot be checked.`);
    if (plan) lines.push(`Plan ${label}: DEM ${plan.gridId || 'no ID'}, selection ${plan.selectedId || 'none; candidates not assessable/not chosen'}. Earth and target keep their own points; no geographic homology is assumed.`);
    else lines.push(`${label}: no regional plan; no touchdown zone is determined.`);
    for (const key of ['altitudeM','verticalSpeedMs','horizontalSpeedMs','propellantKg','thrustN']) if (!finite(run[key])) r.missing.add(`${root}.runs.${side}.${key}`);
  }
  lines.push('The analog serves to prepare operations and compare regional geometry; gravity, atmosphere/vacuum and radiation require dedicated tests. A 37.5 m DEM spacing does not resolve landing legs, rocks or cavities. Idealized navigation inspired by references; no NASA TRN/vision implemented. Mars covers only the final powered segment, without entry or parachutes; the Moon has no atmosphere.');
  for (const limit of (l.limitations || []).slice(0,5)) if (typeof limit==='string') lines.push(limit);
  return {title:'Simulated final descent',lines};
}

/**
 * answerLocally(question, context) → { answer, provider:"rules", model:"rules-v1", grounded, generatedAt, disclaimer }.
 * Nunca lanza: con contexto vacío responde qué datos faltan.
 */
export function answerLocally(question, context) {
  const ctx = context && typeof context === 'object' ? context : {};
  const r = makeReport(ctx);
  const flags = { nogo: [], caution: [] };
  const intents = detectIntents(question);
  const all = intents.includes('summary') ? ['thermal', 'energy', 'terrain', 'wind', 'similarity', ...(ctx.analogyAudit ? ['breakdown'] : []), ...(ctx.landing || ctx.analogyAudit?.landing ? ['landing'] : []), ...(ctx.processes ? ['window'] : [])] : intents;
  const builders = { landing: landingSection, breakdown: breakdownSection, thermal: thermalSection, energy: energySection, terrain: terrainSection, wind: windSection, similarity: similaritySection, window: windowSection };
  let sections;
  try {
    sections = all.map((k) => builders[k](ctx, r, flags));
  } catch {
    sections = [{ title: 'Status', lines: ['Unexpected context format: the report could not be generated.'] }];
  }

  const scen = ctx.scenario || {};
  const header = `FLIGHT DIRECTOR · ${scen.title || 'Unidentified scenario'}`
    + (ctx.earth?.name || ctx.target?.name ? ` (${ctx.earth?.name || 'Earth?'} ↔ ${ctx.target?.name || 'target?'})` : '');
  if (scen.title) r.use('scenario.title');
  const body = sections.map((s) => `${s.title.toUpperCase()}\n${s.lines.map((l) => (l.startsWith('·') ? `  ${l}` : `- ${l}`)).join('\n')}`).join('\n\n');

  let verdict;
  if (all.includes('landing')) verdict = 'Exploratory mission and simulated test; flight state and its tolerances do not authorize operations or certify a landing.';
  else if (all.includes('breakdown') && !flags.nogo.length && !flags.caution.length) verdict = 'Test pending dedicated validation; the audit does not authorize GO/NO-GO.';
  else if (flags.nogo.length) verdict = `NO-GO (illustrative): ${flags.nogo.join('; ')}.`;
  else if (flags.caution.length) verdict = `GO with cautions (illustrative): ${flags.caution.join('; ')}.`;
  else if (r.grounded.size) verdict = 'GO (illustrative) with the available data; no alerts at the prototype thresholds.';
  else verdict = 'Not enough data to recommend GO/NO-GO.';

  const missingTop = [...r.missing].filter((p) => !r.grounded.has(p));
  const gaps = missingTop.length ? `\n\nData not available in the context: ${missingTop.slice(0, 8).join(', ')}${missingTop.length > 8 ? '…' : ''}.` : '';

  return {
    answer: `${header}\n\n${body}\n\nRECOMMENDATION\n- ${verdict}${gaps}`,
    provider: 'rules',
    model: 'rules-v1',
    grounded: [...r.grounded],
    generatedAt: new Date().toISOString(),
    disclaimer: DISCLAIMER,
  };
}
